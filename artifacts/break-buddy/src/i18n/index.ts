// Keep <html dir> in sync for RTL languages
const RTL_LANGS = new Set(["ar"]);
export function applyDocumentDir(lng: string) {
  document.documentElement.dir = RTL_LANGS.has(lng) ? "rtl" : "ltr";
  document.documentElement.lang = lng;
}

